import assert from 'node:assert/strict'
import fs from 'node:fs'
import ts from 'typescript'
const transpile=source=>ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText
const uri=source=>'data:text/javascript;base64,'+Buffer.from(source).toString('base64')
const modelURL=uri(transpile(fs.readFileSync('src/model.ts','utf8')))
const {fixtures}=await import(modelURL)
const module=await import(uri(transpile(fs.readFileSync('src/team-model.ts','utf8')).replace("'./model'",JSON.stringify(modelURL))))
const {fixtureLineup,emptyLineup,saveLineup,publicLineup,assignPlayer,removePlayer,validateLineup,orderedPlayers,applicantPool}=module
const original=fixtureLineup(),player=original.teams[0].players[0]
const moved=assignPlayer(original,'B',player)
assert.equal(original.teams[0].players.length,7)
assert.equal(moved.teams[0].players.length,6)
assert.equal(moved.teams[1].players.length,8)
assert.equal(moved.teams.flatMap(t=>t.players).filter(p=>p.id===player.id).length,1)
const privateRecord=saveLineup(undefined,moved,original)
assert.deepEqual(publicLineup(privateRecord,true),original)
assert.deepEqual(privateRecord.draft,moved)
const sharedRecord=saveLineup(privateRecord,moved,original,true)
assert.deepEqual(publicLineup(sharedRecord,true),moved)
const next=removePlayer(moved,player.id)
const after=saveLineup(sharedRecord,next,moved)
assert.deepEqual(after.shared,moved)
assert.deepEqual(after.draft,next)
next.teams[0].title='changed outside store'
assert.equal(after.draft.teams[0].title,'A팀')
const unpublished=saveLineup(undefined,moved,undefined)
assert.equal(publicLineup(unpublished,false),undefined)
assert.ok(validateLineup(emptyLineup()))
assert.equal(validateLineup(original),'')
const duplicate=fixtureLineup();duplicate.teams[1].players.push({...player})
assert.ok(validateLineup(duplicate).includes('중복'))
assert.equal(orderedPlayers([...original.teams[0].players].reverse())[0].position,'세터')
assert.equal(applicantPool(fixtures[0],false,false).length,0)
assert.equal(applicantPool(fixtures[0],false,true)[0].name,'김나래')
console.log('Team checks: 17 passed (private drafts, immutable public snapshot, publication, unique movement, removal, validation, setter first, new session applicants).')

const {isInLineup,canReadTeams,registrationMode,groupCandidates}=module
assert.equal(registrationMode(true,'2026-09-26T18:00','2026-09-23T12:00'),'waiting')
assert.equal(registrationMode(false,'2026-09-26T18:00','2026-09-23T12:00'),'applied')
assert.equal(registrationMode(false,'2026-09-23T11:00','2026-09-23T12:00'),'waiting')
const hiddenFixture=publicLineup(undefined,true,true)
assert.equal(isInLineup(hiddenFixture,'김나래'),false)
assert.equal(canReadTeams(false,false,hiddenFixture,'김나래'),false)
assert.equal(canReadTeams(true,false,hiddenFixture,'김나래'),true)
assert.equal(canReadTeams(false,true,hiddenFixture,'김나래'),true)
const waitingPlayer=module.memberPool.find(p=>p.id==='김나래')
const assignedDraft=assignPlayer(hiddenFixture,'A',waitingPlayer)
const waitingSaved=saveLineup(undefined,assignedDraft,hiddenFixture)
assert.equal(canReadTeams(false,false,publicLineup(waitingSaved,true,true),'김나래'),false)
const waitingPublished=saveLineup(waitingSaved,assignedDraft,hiddenFixture,true)
assert.equal(canReadTeams(false,false,publicLineup(waitingPublished,true,true),'김나래'),true)
const groups=groupCandidates([player],[waitingPlayer],module.memberPool,true)
assert.deepEqual(groups.map(g=>g.label),['신청자','대기자','미신청 회원'])
assert.equal(groups.flatMap(g=>g.players).filter(p=>p.id===waitingPlayer.id).length,1)
console.log('Waiting-list checks: 11 passed (post-publication signup, deadline, access gates, private draft exclusion, published promotion, candidate ordering).')
