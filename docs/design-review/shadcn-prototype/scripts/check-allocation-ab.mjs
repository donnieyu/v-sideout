import assert from 'node:assert/strict'
import fs from 'node:fs'
import ts from 'typescript'
const load=(path,imports={})=>{
 let source=ts.transpileModule(fs.readFileSync(path,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText
 for(const [key,value] of Object.entries(imports))source=source.replaceAll(`'${key}'`,JSON.stringify(value))
 return 'data:text/javascript;base64,'+Buffer.from(source).toString('base64')
}
const model=load('src/model.ts')
const team=load('src/team-model.ts',{'./model':model})
const board=load('src/position-board-model.ts',{'./team-model':team})
const {initialReview,reviewReducer:act,isPending,reviewCandidates}=await import(load('src/allocation-ab-model.ts',{'./position-board-model':board}))
let n=0
const check=(a,b)=>{assert.deepEqual(a,b);n++}
const target={teamId:'A',slotId:'2'}
const start=initialReview(), before=structuredClone(start)
const open=act(start,{type:'open',target})
check(open.target,target)
check(reviewCandidates.length,18)
check(reviewCandidates.filter(p=>p.position==='세터').length,3)
check(start.board.flatMap(t=>t.slots).every(s=>s.playerId===null),true)
const picked=act(open,{type:'pick',playerId:'김도윤'})
check(isPending(picked),true)
check(picked.board,start.board)
check(act(picked,{type:'pick',playerId:'김도윤'}).pendingId,'김도윤')
check(act(picked,{type:'open',target:{teamId:'B',slotId:'2'}}),picked)
check(act(picked,{type:'review'}),picked)
const discarded=act(picked,{type:'discard',close:true})
check(discarded.board,start.board)
check(discarded.target,null)
const applied=act(picked,{type:'apply',close:false})
check(applied.board[0].slots[2].playerId,'김도윤')
check(isPending(applied),false)
check(applied.target,target)
const replace=act(act(applied,{type:'pick',playerId:'서유진'}),{type:'apply',close:true})
check(replace.board[0].slots[2].playerId,'서유진')
check(replace.board.flatMap(t=>t.slots).some(s=>s.playerId==='김도윤'),false)
const move=act(act(act(replace,{type:'open',target:{teamId:'B',slotId:'2'}}),{type:'pick',playerId:'서유진'}),{type:'apply',close:false})
check(move.board[0].slots[2].playerId,null)
check(move.board[1].slots[2].playerId,'서유진')
check(move.board.flatMap(t=>t.slots).filter(s=>s.playerId==='서유진').length,1)
const clear=act(move,{type:'pick',playerId:null})
check(isPending(clear),true)
check(act(clear,{type:'discard',close:false}).pendingId,'서유진')
check(act(clear,{type:'apply',close:true}).board[1].slots[2].playerId,null)
check(act(open,{type:'pick',playerId:'unknown'}),open)
check(act(start,{type:'open',target:{teamId:'unknown',slotId:'2'}}),start)
check(act(start,{type:'pick',playerId:'김도윤'}),start)
check(start,before)
const reviewed=act(applied,{type:'review'})
check(reviewed.reviewed,true)
check(act(act(reviewed,{type:'open',target:{teamId:'B',slotId:'2'}}),{type:'pick',playerId:'서유진'}).reviewed,true)
check(act(act(act(reviewed,{type:'open',target:{teamId:'B',slotId:'2'}}),{type:'pick',playerId:'서유진'}),{type:'apply',close:true}).reviewed,false)
check(act(applied,{type:'reset'}),initialReview())
check(initialReview().board.flatMap(t=>t.slots).filter(s=>s.playerId).length,0)
let flow=act(initialReview(),{type:'select-role',role:'레프트'})
check(flow?.target,{teamId:'A',slotId:'0'})
flow=act(flow,{type:'continuous-assign',playerId:'강현우'})
check(flow.board[0].slots[0].playerId,'강현우')
check(flow.target,{teamId:'A',slotId:'3'})
check(isPending(flow),false)
flow=act(flow,{type:'continuous-assign',playerId:'박지훈'})
check(flow.target,{teamId:'B',slotId:'0'})
flow=act(flow,{type:'open',target:{teamId:'C',slotId:'0'}})
flow=act(flow,{type:'continuous-assign',playerId:'김서현'})
check(flow.target,{teamId:'C',slotId:'3'})
flow=act(flow,{type:'continuous-assign',playerId:'이수민'})
check(flow.target,{teamId:'B',slotId:'0'})
check(act(flow,{type:'continuous-assign',playerId:'강현우'}),flow)
check(act(flow,{type:'continuous-assign',playerId:'unknown'}),flow)
const occupied=act(flow,{type:'open',target:{teamId:'A',slotId:'0'}})
const replaced=act(occupied,{type:'continuous-assign',playerId:'신하은'})
check(replaced.board[0].slots[0].playerId,'신하은')
check(replaced.board.flatMap(t=>t.slots).some(s=>s.playerId==='강현우'),false)
check(replaced.target,occupied.target)
flow=act(flow,{type:'continuous-assign',playerId:'신하은'})
check(flow.target,{teamId:'B',slotId:'3'})
flow=act(flow,{type:'continuous-assign',playerId:'정하준'})
check(flow.target,{teamId:'B',slotId:'3'})
check(flow.board.flatMap(t=>t.slots).filter(s=>s.position==='레프트'&&s.playerId).length,6)
check(flow.board.flatMap(t=>t.slots).filter(s=>s.position==='센터'&&s.playerId).length,0)
check(act(flow,{type:'select-role',role:'레프트'}).target,null)
const staleRelease=act(flow,{type:'release',target:{teamId:'A',slotId:'0'},playerId:'wrong'})
check(staleRelease,flow)
const released=act(flow,{type:'release',target:{teamId:'A',slotId:'0'},playerId:'강현우'})
check(released.board[0].slots[0].playerId,null)
check(released.target,{teamId:'A',slotId:'0'})
check(flow.board[0].slots[0].playerId,'강현우')
check(act(released,{type:'continuous-assign',playerId:'강현우'}).target,{teamId:'A',slotId:'0'})
const partial=act(initialReview(),{type:'select-role',role:'센터'})
check(partial.target,{teamId:'A',slotId:'1'})
check(act(partial,{type:'select-role',role:'라이트'}).target,{teamId:'A',slotId:'5'})
check(act(act(initialReview(),{type:'open',target:{teamId:'C',slotId:'2'}}),{type:'continuous-assign',playerId:'이도현'}).target,{teamId:'A',slotId:'2'})
check(act(act(partial,{type:'review'}),{type:'continuous-assign',playerId:'오수빈'}).reviewed,false)
// Free flow: setters remain a separate first step, then any candidate can fill
// each non-setter place in team order without a position filter.
let free=act(initialReview(),{type:'select-free'})
check(free.target,{teamId:'A',slotId:'0'})
check(act(free,{type:'continuous-assign',playerId:'김도윤',flow:'free'}),free)
free=act(free,{type:'continuous-assign',playerId:'강현우',flow:'free'})
check(free.target,{teamId:'A',slotId:'1'})
free=act(free,{type:'continuous-assign',playerId:'박지훈',flow:'free'})
check(free.target,{teamId:'A',slotId:'3'})
check(act(free,{type:'select-role',role:'세터'}).target,{teamId:'A',slotId:'2'})
// Auto placement keeps manual picks, fills every other place exactly once,
// and puts the three primary setters into the three setter places.
const manual=act(act(initialReview(),{type:'open',target:{teamId:'A',slotId:'0'}}),{type:'continuous-assign',playerId:'강현우'})
const auto=act(manual,{type:'auto-fill'})
check(auto.board[0].slots[0].playerId,'강현우')
check(auto.board.flatMap(t=>t.slots).filter(s=>!!s.playerId).length,18)
check(new Set(auto.board.flatMap(t=>t.slots).flatMap(s=>s.playerId?[s.playerId]:[])).size,18)
check(auto.board.every(t=>t.slots[2].playerId&&reviewCandidates.find(p=>p.id===t.slots[2].playerId)?.position==='세터'),true)
check(auto.reviewed,false)
const shifted=act(act(initialReview(),{type:'open',target:{teamId:'A',slotId:'5'}}),{type:'continuous-assign',playerId:'오수빈'})
const secondaryAuto=act(shifted,{type:'auto-fill'})
check(secondaryAuto.board[0].slots[5].playerId,'오수빈')
check(secondaryAuto.board.flatMap(t=>t.slots).some(s=>s.position==='센터'&&s.playerId&&reviewCandidates.find(p=>p.id===s.playerId)?.secondary==='센터'&&reviewCandidates.find(p=>p.id===s.playerId)?.position!=='센터'),true)
console.log(`Allocation interaction checks: ${n} passed (including cyclic continuous allocation).`)
