import assert from 'node:assert/strict'
import fs from 'node:fs'
import ts from 'typescript'
const transpile=source=>ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText
const uri=source=>'data:text/javascript;base64,'+Buffer.from(source).toString('base64')
const modelURL=uri(transpile(fs.readFileSync('src/model.ts','utf8')))
const teamURL=uri(transpile(fs.readFileSync('src/team-model.ts','utf8')).replace("'./model'",JSON.stringify(modelURL)))
const {candidates,initialBoard,createTeam,addBenchSlot,saveBoard,courtSlots,candidateGroups,prioritizeCandidates,fitsPosition,placeOnBoard,locatePlayer}=await import(uri(transpile(fs.readFileSync('src/position-board-model.ts','utf8')).replace("'./team-model'",JSON.stringify(teamURL))))
let checks=0
const check=(actual,expected)=>{assert.deepEqual(actual,expected);checks++}
const setter=candidates.find(p=>p.position==='세터')
check(fitsPosition(setter,'센터','primary'),true)
check(fitsPosition(setter,'라이트','primary'),true)
check(fitsPosition(setter,'레프트','primary'),false)
const left=candidates.find(p=>p.position==='레프트')
check(fitsPosition(left,'센터','primary'),false)
check(fitsPosition(left,'센터','secondary'),true)
check(fitsPosition(left,'라이트','all'),true)
check(candidates.every(p=>fitsPosition(p,'교대','primary')),true)
const original=initialBoard(),snapshot=structuredClone(original)
const moved=placeOnBoard(original,'B','1',setter.id)
check(locatePlayer(moved,setter.id).team.id,'B')
check(locatePlayer(moved,setter.id).slot.position,'센터')
check(moved.flatMap(t=>t.slots).filter(s=>s.playerId===setter.id).length,1)
check(moved[0].slots[2].playerId,null)
check(locatePlayer(moved,'윤지호'),undefined)
check(candidates.some(p=>p.id==='윤지호'),true)
check(setter.position,'세터')
check(original,snapshot)
check(locatePlayer(placeOnBoard(moved,'B','1',null),setter.id),undefined)
check(placeOnBoard(original,'missing','0',setter.id),original)
check(placeOnBoard(original,'A','missing',setter.id),original)
for(const team of original){
 const slots=courtSlots(team)
 check(slots.slice(0,3).some(s=>candidates.find(p=>p.id===s.playerId)?.position==='세터'),true)
 check(slots.map(s=>s.playerId).sort(),team.slots.map(s=>s.playerId).sort())
}
const empty=createTeam('D')
check(courtSlots(empty).map(s=>s.position),['레프트','센터','세터','레프트','센터','라이트'])
check(empty.slots.filter(s=>s.position==='세터').length,1)
check(empty.slots.filter(s=>s.position==='라이트').length,1)
const reassigned=placeOnBoard(original,'B','4',setter.id)
check(reassigned[1].slots[4].position,'센터')
check(courtSlots(reassigned[1])[2].position,'세터')
check(original,snapshot)
check(prioritizeCandidates([setter,left,...candidates.filter(p=>p.position==='센터')],'센터').map(p=>p.id),[...candidates.filter(p=>p.position==='센터').map(p=>p.id),left.id,setter.id])
check(prioritizeCandidates(candidates,'레프트'),candidates)
check(fitsPosition(setter,'세터','primary'),true)
check(fitsPosition(left,'세터','primary'),false)
const removed=placeOnBoard(original,'A','2',null)
check(courtSlots(removed[0])[2].position,'세터')
check(courtSlots(removed[0])[2].playerId,null)
const benches=addBenchSlot(addBenchSlot(addBenchSlot(original,'A'),'A'),'A')
check(benches[0].slots.filter(s=>s.position==='교대').length,3)
check(new Set(benches[0].slots.map(s=>s.id)).size,9)
const filledBench=placeOnBoard(benches,'A','bench-2','오수빈')
const saved=saveBoard(filledBench)
check(saved[0].slots.filter(s=>s.position==='교대').map(s=>s.playerId),['오수빈'])
check(saved[0].slots.filter(s=>s.position!=='교대').length,6)
check(saved[0].slots[1].playerId,null)
check(filledBench[0].slots.length,9)
check(original,snapshot)
check(new Set(addBenchSlot(saved,'A')[0].slots.map(s=>s.id)).size,8)
check(saveBoard(saved),saved)
check(saveBoard(placeOnBoard(filledBench,'A','bench-2',null))[0].slots.length,6)
const groups=candidateGroups(candidates,original,'센터')
check(groups.map(g=>g.label),['미배정 · 신청자','미배정 · 대기자','배정됨 · 신청자'])
const flat=groups.flatMap(g=>g.people)
const firstUsed=flat.findIndex(p=>locatePlayer(original,p.id))
check(flat.slice(firstUsed).every(p=>!!locatePlayer(original,p.id)),true)
check(flat.length,candidates.length)
check(new Set(flat.map(p=>p.id)).size,candidates.length)
check(groups[0].people[0].position,'센터')
check(candidateGroups([],original,'센터'),[])
console.log(`Position board checks: ${checks} passed (fixed setter slot, center ordering, eligibility, unique movement, replacement, immutability).`)
